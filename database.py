import os

import psycopg
from psycopg.rows import dict_row


DEFAULT_DATABASE_URL = (
    "postgresql://postgres:postgres@localhost:5432/studyflow"
)
DATABASE_URL = os.environ.get(
    "STUDYFLOW_DB_URL",
    DEFAULT_DATABASE_URL,
)


def configure_database(database_url):
    """Configure the PostgreSQL DSN used by future connections."""
    global DATABASE_URL
    DATABASE_URL = str(database_url)


def get_database_url():
    """Return the PostgreSQL DSN used by new connections."""
    return DATABASE_URL


def get_connection():
    """Create and return a connection to the PostgreSQL database."""
    return psycopg.connect(
        get_database_url(),
        row_factory=dict_row,
    )


def initialize_database():
    """Create all StudyFlow database tables if they do not exist."""

    connection = get_connection()

    try:
        cursor = connection.cursor()

        # --------------------
        # USERS
        # --------------------
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL UNIQUE,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                display_name TEXT,
                created_at TEXT NOT NULL
                    DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS'),
                updated_at TEXT NOT NULL
                    DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS')
            )
        """)

        # --------------------
        # USER PREFERENCES
        # One-to-one relationship with users
        # --------------------
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS user_preferences (
                user_id INTEGER PRIMARY KEY,
                theme TEXT NOT NULL DEFAULT 'Dark',
                color_scheme TEXT NOT NULL DEFAULT 'Purple + Pink',
                language TEXT NOT NULL DEFAULT 'English',

                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE
            )
        """)

        # --------------------
        # COURSES
        # --------------------
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS courses (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER,
                name TEXT NOT NULL,
                instructor TEXT,
                credits INTEGER,
                semester TEXT,
                color TEXT,
                is_active BOOLEAN NOT NULL DEFAULT TRUE,

                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE
            )
        """)

        # --------------------
        # ASSIGNMENTS
        # --------------------
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS assignments (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                course_id INTEGER NOT NULL,
                title TEXT NOT NULL,
                description TEXT,
                deadline TEXT,
                status TEXT NOT NULL DEFAULT 'Not Started',
                priority TEXT NOT NULL DEFAULT 'Medium',
                progress INTEGER NOT NULL DEFAULT 0
                    CHECK(progress BETWEEN 0 AND 100),

                FOREIGN KEY (course_id)
                    REFERENCES courses(id)
                    ON DELETE CASCADE
            )
        """)

        # --------------------
        # RESOURCES
        # --------------------
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS resources (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER,
                course_id INTEGER,
                title TEXT NOT NULL,
                resource_type TEXT NOT NULL,
                author TEXT,
                category TEXT,
                url TEXT,
                status TEXT NOT NULL DEFAULT 'Not Started',
                notes TEXT,
                created_at TEXT NOT NULL
                    DEFAULT to_char(now(), 'YYYY-MM-DD HH24:MI:SS'),

                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE,

                FOREIGN KEY (course_id)
                    REFERENCES courses(id)
                    ON DELETE SET NULL
            )
        """)

        # --------------------
        # STUDY SESSIONS
        # --------------------
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS study_sessions (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER,
                course_id INTEGER NOT NULL,
                study_date TEXT NOT NULL,
                duration_minutes INTEGER NOT NULL
                    CHECK(duration_minutes > 0),
                notes TEXT,

                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE,

                FOREIGN KEY (course_id)
                    REFERENCES courses(id)
                    ON DELETE CASCADE
            )
        """)

        # --------------------
        # CALENDAR EVENTS
        # --------------------
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS calendar_events (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER,
                course_id INTEGER,
                title TEXT NOT NULL,
                event_type TEXT NOT NULL,
                start_datetime TEXT NOT NULL,
                end_datetime TEXT,
                description TEXT,

                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE,

                FOREIGN KEY (course_id)
                    REFERENCES courses(id)
                    ON DELETE SET NULL
            )
        """)

        # --------------------
        # TAGS
        # --------------------
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS tags (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL UNIQUE
            )
        """)

        # --------------------
        # RESOURCE TAGS
        # Many-to-Many relationship
        # --------------------
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS resource_tags (
                resource_id INTEGER NOT NULL,
                tag_id INTEGER NOT NULL,

                PRIMARY KEY (resource_id, tag_id),

                FOREIGN KEY (resource_id)
                    REFERENCES resources(id)
                    ON DELETE CASCADE,

                FOREIGN KEY (tag_id)
                    REFERENCES tags(id)
                    ON DELETE CASCADE
            )
        """)

        # --------------------
        # USER OWNERSHIP
        # Add ownership columns to databases created before this change.
        # Columns stay nullable so existing service calls keep working
        # until the service layer is migrated.
        # --------------------
        for table in (
            "courses",
            "resources",
            "study_sessions",
            "calendar_events",
        ):
            cursor.execute(f"""
                ALTER TABLE {table}
                    ADD COLUMN IF NOT EXISTS user_id INTEGER
                    REFERENCES users(id)
                    ON DELETE CASCADE
            """)

        # --------------------
        # USER OWNERSHIP INDEXES
        # --------------------
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_courses_user_id
                ON courses (user_id)
        """)
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_resources_user_id
                ON resources (user_id)
        """)
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_study_sessions_user_id
                ON study_sessions (user_id)
        """)
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_calendar_events_user_id
                ON calendar_events (user_id)
        """)

        connection.commit()

    finally:
        connection.close()


if __name__ == "__main__":
    initialize_database()
    print("StudyFlow database initialized successfully!")
